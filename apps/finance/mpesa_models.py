"""
M-Pesa transaction tracking models.

Every STK Push and C2B payment attempt is logged here for:
  - Audit trail
  - Reconciliation
  - Debugging failed payments
  - Preventing duplicate processing
"""
from django.db import models


class SchoolMpesaConfig(models.Model):
    """Stores the specific Paybill and Daraja API keys for each school."""
    school = models.OneToOneField(
        'schools.School', on_delete=models.CASCADE, related_name='mpesa_config'
    )
    paybill_number = models.CharField(
        max_length=20, blank=True, null=True,
        help_text="The Business Shortcode / Paybill number for this school"
    )
    consumer_key = models.CharField(max_length=255, blank=True, null=True)
    consumer_secret = models.CharField(max_length=255, blank=True, null=True)
    passkey = models.CharField(max_length=255, blank=True, null=True)
    callback_url = models.URLField(
        max_length=500, blank=True, null=True,
        help_text="Auto-generated by the system for Safaricom C2B"
    )
    is_active = models.BooleanField(default=True)

    def __str__(self):
        return f"{self.school.name} — Paybill {self.paybill_number}"


class MpesaTransaction(models.Model):
    """A single M-Pesa transaction attempt (STK Push, C2B, or Manual)."""

    class Status(models.TextChoices):
        PENDING  = 'pending',  'Pending'
        SUCCESS  = 'success',  'Success'
        FAILED   = 'failed',   'Failed'
        CANCELLED= 'cancelled','Cancelled by user'
        TIMEOUT  = 'timeout',  'Timed out'

    class Type(models.TextChoices):
        STK_PUSH = 'stk_push', 'STK Push'
        C2B      = 'c2b',      'C2B (Paybill)'
        MANUAL   = 'manual',   'Manual Entry'

    class Purpose(models.TextChoices):
        FEES   = 'fees',   'School Fees'
        WALLET = 'wallet', 'Student Wallet Top-up'
        OTHER  = 'other',  'Other Payment'


    school = models.ForeignKey(
        'schools.School', on_delete=models.CASCADE,
        related_name='mpesa_transactions',
        null=True, blank=True,
    )
    # Link to student helps wallet top-ups
    student = models.ForeignKey(
        'students.Student', on_delete=models.SET_NULL,
        null=True, blank=True, related_name='mpesa_transactions',
    )
    invoice = models.ForeignKey(
        'finance.Invoice', on_delete=models.SET_NULL,
        null=True, blank=True, related_name='mpesa_transactions',
    )
    payment = models.OneToOneField(
        'finance.Payment', on_delete=models.SET_NULL,
        null=True, blank=True, related_name='mpesa_transaction',
    )

    transaction_type = models.CharField(
        max_length=10, choices=Type.choices, default=Type.STK_PUSH
    )
    
    # NEW: Routing fields for Option B
    purpose = models.CharField(
        max_length=10, choices=Purpose.choices, default=Purpose.FEES
    )
    bill_ref_number = models.CharField(
        max_length=100, blank=True, null=True, 
        help_text="The account number the parent typed (e.g. ADM1024-WAL)"
    )

    phone = models.CharField(max_length=15)
    amount = models.DecimalField(max_digits=10, decimal_places=2)

    # Safaricom IDs
    merchant_request_id = models.CharField(
        max_length=100, blank=True, default='', db_index=True
    )
    checkout_request_id = models.CharField(
        max_length=100, blank=True, default='', db_index=True
    )
    mpesa_receipt_number = models.CharField(
        max_length=50, blank=True, default='', db_index=True,
        help_text="Populated on success. Unique per transaction."
    )

    # Result
    result_code = models.IntegerField(null=True, blank=True)
    result_description = models.TextField(blank=True, default='')
    status = models.CharField(
        max_length=10, choices=Status.choices, default=Status.PENDING
    )

    # Raw audit
    raw_request = models.JSONField(default=dict, blank=True)
    raw_callback = models.JSONField(default=dict, blank=True)

    initiated_by = models.ForeignKey(
        'accounts.User', on_delete=models.SET_NULL,
        null=True, blank=True, related_name='mpesa_initiated'
    )

    created_at = models.DateTimeField(auto_now_add=True)
    completed_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        ordering = ['-created_at']
        indexes = [
            models.Index(fields=['school', 'status']),
            models.Index(fields=['checkout_request_id']),
            models.Index(fields=['mpesa_receipt_number']),
        ]

    def __str__(self):
        return f"{self.get_transaction_type_display()} — {self.phone} — KES {self.amount} ({self.get_status_display()})"

    @property
    def is_successful(self):
        return self.status == self.Status.SUCCESS

    @property
    def is_pending(self):
        return self.status == self.Status.PENDING
    
class PlatformMpesaConfig(models.Model):
    """SaaS Owner's Paybill details for collecting school subscriptions."""
    paybill_number = models.CharField(max_length=20, help_text="e.g., 400200")
    account_type = models.CharField(
        max_length=20, 
        choices=[('paybill', 'Paybill'), ('till', 'Buy Goods (Till)')], 
        default='paybill'
    )
    consumer_key = models.CharField(max_length=255, blank=True, null=True)
    consumer_secret = models.CharField(max_length=255, blank=True, null=True)
    passkey = models.CharField(max_length=255, blank=True, null=True)
    
    # This is where Safaricom will send the confirmation for subscriptions
    callback_url = models.URLField(max_length=500, blank=True, null=True)
    
    is_active = models.BooleanField(default=True)
    updated_at = models.DateTimeField(auto_now=True)

    def __str__(self):
        return f"Platform {self.get_account_type_display()}: {self.paybill_number}"